#!/usr/bin/env bash
# Register the ACP Chat native messaging host with Chrome-family browsers (macOS/Linux).
#
# Chrome launches native hosts with a minimal environment, so this script
# writes a small wrapper that pins the absolute node path and your current
# PATH (so harnesses like kiro-cli / npx / kimi can be found).
set -euo pipefail

HOST_NAME="dev.acp_chat.host"
ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
HOST_DIR="$ROOT/host"
WRAPPER="$HOST_DIR/acp-chat-host"
NODE_BIN="$(command -v node || true)"

if [[ -z "$NODE_BIN" ]]; then
  echo "error: node not found on PATH" >&2
  exit 1
fi

# The extension id is derived from the public key pinned in manifest.json.
EXT_ID="$("$NODE_BIN" -e '
  const m = require(process.argv[1]);
  const h = require("crypto").createHash("sha256").update(Buffer.from(m.key, "base64")).digest("hex").slice(0, 32);
  process.stdout.write([...h].map(c => String.fromCharCode(97 + parseInt(c, 16))).join(""));
' "$ROOT/extension/manifest.json")"

cat > "$WRAPPER" <<EOF
#!/usr/bin/env bash
# Generated by host/install.sh — do not edit; re-run the installer instead.
export PATH=$(printf '%q' "$PATH")
exec $(printf '%q' "$NODE_BIN") $(printf '%q' "$HOST_DIR/host.js") "\$@"
EOF
chmod 755 "$WRAPPER"

MANIFEST=$(cat <<EOF
{
  "name": "$HOST_NAME",
  "description": "ACP Chat native host (spawns local ACP agent harnesses)",
  "path": "$WRAPPER",
  "type": "stdio",
  "allowed_origins": ["chrome-extension://$EXT_ID/"]
}
EOF
)

if [[ "$(uname)" == "Darwin" ]]; then
  BASE="$HOME/Library/Application Support"
  TARGETS=(
    "$BASE/Google/Chrome"
    "$BASE/Google/Chrome Beta"
    "$BASE/Google/Chrome Canary"
    "$BASE/Google/Chrome for Testing"
    "$BASE/Chromium"
    "$BASE/BraveSoftware/Brave-Browser"
    "$BASE/Microsoft Edge"
  )
else
  BASE="${XDG_CONFIG_HOME:-$HOME/.config}"
  TARGETS=("$BASE/google-chrome" "$BASE/google-chrome-beta" "$BASE/chromium" "$BASE/BraveSoftware/Brave-Browser" "$BASE/microsoft-edge")
fi

# Optional extra profile dir (e.g. a test --user-data-dir).
if [[ -n "${ACP_CHAT_EXTRA_PROFILE_DIR:-}" ]]; then TARGETS+=("$ACP_CHAT_EXTRA_PROFILE_DIR"); fi

installed=0
for dir in "${TARGETS[@]}"; do
  [[ -d "$dir" ]] || continue
  mkdir -p "$dir/NativeMessagingHosts"
  printf '%s\n' "$MANIFEST" > "$dir/NativeMessagingHosts/$HOST_NAME.json"
  echo "installed  $dir/NativeMessagingHosts/$HOST_NAME.json"
  installed=$((installed + 1))
done

if [[ $installed -eq 0 ]]; then
  echo "warning: no Chrome-family browser profile directory found" >&2
fi
echo
echo "extension id: $EXT_ID"
echo "host wrapper: $WRAPPER"
echo "harness config: \${ACP_CHAT_CONFIG:-~/.config/acp-chat/harnesses.json} (falls back to host/harnesses.json)"
